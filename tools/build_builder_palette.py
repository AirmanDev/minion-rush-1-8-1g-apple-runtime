#!/usr/bin/env python3
"""Generate native SwiftUI and Win32 color tokens from one source."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config/builder_theme.json"
WIN = ROOT / "src/windows/builder_palette.h"
MAC = ROOT / "installer/BuilderPalette.swift"

NAMES = (
    ("background", "BACKGROUND"), ("card", "CARD"), ("border", "CARD_EDGE"),
    ("navy", "NAVY"), ("navyMuted", "NAVY_MUTED"),
    ("text", "TEXT"), ("muted", "MUTED"), ("disabled", "DISABLED"),
    ("field", "FIELD"), ("fieldOff", "FIELD_OFF"),
    ("fieldEdge", "FIELD_EDGE"), ("edgeHot", "EDGE_HOT"),
    ("hover", "HOVER"), ("pressed", "PRESSED"),
    ("gold", "GOLD"), ("goldHot", "GOLD_HOT"),
    ("goldDown", "GOLD_DOWN"), ("track", "TRACK"),
    ("idle", "IDLE"), ("success", "GOOD"), ("failure", "BAD"),
)


def build_files() -> dict[Path, str]:
    values = json.loads(SOURCE.read_text(encoding="ascii"))
    if not isinstance(values, dict) or set(values) != {name for name, _ in NAMES}:
        raise ValueError("invalid builder color tokens")
    win = ["/* Generated by tools/build_builder_palette.py; edit config/builder_theme.json. */",
           "#ifndef MINION_BUILDER_PALETTE_H", "#define MINION_BUILDER_PALETTE_H"]
    mac = ["// Generated by tools/build_builder_palette.py; edit config/builder_theme.json.",
           "import SwiftUI", "", "enum BuilderPalette {"]
    for name, c_name in NAMES:
        entry = values[name]
        if not isinstance(entry, list) or len(entry) != 3 or any(
                type(channel) is not int or not 0 <= channel <= 255 for channel in entry):
            raise ValueError("invalid RGB color: " + name)
        r, g, b = entry
        win.append(f"#define COL_{c_name:<12} RGB({r}, {g}, {b})")
        mac.append(f"  static let {name} = Color(red: {r} / 255, green: {g} / 255, "
                   f"blue: {b} / 255)")
    win.extend(["#endif", ""])
    mac.extend(["}", ""])
    return {WIN: "\n".join(win), MAC: "\n".join(mac)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in build_files().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="ascii") != expected:
                print("Outdated generated Builder palette:", path, file=sys.stderr)
                return 1
        else:
            path.write_text(expected, encoding="ascii")
    print("Mac/Windows palette matches config/builder_theme.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
